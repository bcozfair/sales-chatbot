/**
 * สัญญาณ "ตัวเลขข้างเมนูอาจเปลี่ยนแล้ว นับใหม่ได้" — ตัวนับอยู่ใน AdminApp.tsx ที่เดียว
 *
 * ทำไมต้องมี: ตัวเลขข้างเมนู (อนุมัติราคา · ผู้ติดต่อเพิ่มเอง · สินค้าเพิ่มเอง) **คือการแจ้งเตือน
 * ของระบบนี้** เพราะห้ามใช้ LINE push (กฎเหล็กของ CLAUDE.md) · เดิมนับใหม่เฉพาะตอนเปลี่ยนแท็บ
 * ⇒ เจ้าของแจ้ง 2026-10-02 ว่าตัวเลขไม่ตามข้อมูลใหม่ ต้องเปลี่ยนหน้าหรือรีเฟรชก่อน ซึ่งแปลว่าคำขอ
 * ที่เพิ่งเข้ามาไม่มีอะไรบอกใครจนกว่าเขาจะบังเอิญกดเมนูอื่น
 *
 * นับใหม่เมื่อ (ตัวรับอยู่ใน AdminApp.tsx):
 *   1. หน้าใดหน้าหนึ่งเพิ่งเขียนสำเร็จ — เรียก `notifyBadgesChanged()` ไฟล์นี้
 *   2. แท็บกลับมาให้เห็น / หน้าต่างได้โฟกัส — คนเพิ่งกลับมาดู คือจังหวะที่ตัวเลขมีความหมายที่สุด
 *   3. ทุก `BADGE_POLL_MS` **เฉพาะตอนเห็นหน้าอยู่** — รับของที่คนอื่นเขียน (อีกเครื่อง · อีกคน)
 *
 * ทางที่ไม่ได้เลือก:
 *   - **ส่ง callback ลงไปทุกหน้าผ่าน props** — ต้องร้อยผ่านหน้าและ modal หลายชั้น (LocalProductModal
 *     ถูกเปิดจากสามหน้า) ลืมเส้นเดียวก็เงียบ · event ของ window ไม่ต้องรู้ว่าใครฟังอยู่
 *   - **ห่อ window.fetch แล้วจับ URL เอง** — AuthContext ห่อ fetch ไว้แล้วเรื่อง 401 ซ้อนอีกชั้นคือ
 *     ลำดับการห่อที่ไม่มีใครเห็น และการเดาจากรูป URL พลาดเงียบ ๆ ทุกครั้งที่มีเส้นใหม่ที่เปลี่ยนตัวนับ
 *   - **SSE / websocket** — ไม่มีโครงสร้างรองรับ (proxy · reconnect · auth) และเกินความจำเป็นของ
 *     ตัวเลขที่ช้าได้เป็นนาที
 *
 * ทำไม 60 วิ: ค่าใช้จ่ายไม่ใช่ตัว COUNT (วัด 2026-10-02 ~0.02 ms บน partial index) แต่คือ
 * **ทุกครั้งที่เรียก /count = 1 แถวใน `api_logs`** ⇒ ถี่กว่านี้คือ log ที่โตเปล่า ๆ ·
 * และไม่นับเลยตอนแท็บซ่อน (เปิดทิ้งไว้ทั้งคืน = 0 แถว)
 */

/** ชื่อ event บน window — `scripts/diag/sidebarBadgesLiveUi.ts` อ่านค่านี้จากซอร์สไปใช้ */
export const BADGES_CHANGED_EVENT = 'primus:badges-changed';

/** รอบนับเองตอนเห็นหน้า — ดูเหตุผลข้างบน */
export const BADGE_POLL_MS = 60_000;

/**
 * สัญญาณที่มาติด ๆ กัน (โฟกัส + เห็นหน้าเกิดพร้อมกันตอนสลับแท็บ · หน้าเดียวแจ้งสองครั้ง)
 * รวมเป็นรอบเดียวภายในช่วงนี้ — ไม่ใช่ยิงสามรอบขนานกัน
 */
export const BADGE_COALESCE_MS = 150;

/** เรียกหลังเขียนสำเร็จทุกครั้งที่อาจทำให้ตัวเลขข้างเมนูเปลี่ยน · เรียกเกินไม่เสียหาย (นับใหม่หนึ่งรอบ) */
export function notifyBadgesChanged(): void {
  window.dispatchEvent(new CustomEvent(BADGES_CHANGED_EVENT));
}
