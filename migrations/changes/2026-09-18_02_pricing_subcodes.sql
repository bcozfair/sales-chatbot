-- ตารางรหัสย่อยของโมดูล "คิดราคาสินค้าสั่งทำ" (services/pricingLab/)
--
-- เจ้าของสั่ง 2026-09-18: เอาเครื่องคิดราคาที่ทำไว้ใน prototypes/pricing/ เข้าหน้าแอดมินจริง
-- เพื่อให้แอดมินล็อกอินเข้าไปทดลองใช้ได้ **แต่ยังไม่ต่อกับใบเสนอราคา คิดราคาให้ดูอย่างเดียว**
-- และต้องถอดออกได้ทุกเมื่อระหว่างที่ดีไซน์ยังไม่นิ่ง ⇒ ถอดโมดูล = DROP ตารางนี้ทิ้งได้เลย
-- ไม่มีตารางเดิมของระบบอ้างถึงมัน และไม่มี FK ชี้เข้ามา
--
-- "รหัสย่อย" คือหนึ่งท่อนในรหัสสินค้าที่ตัวเลขไม่ได้บอกความหมาย เช่น `-BU` `S000` `(M8)`
-- ไฟล์ราคาแทบไม่มีที่ไหนเขียนว่ามันแปลว่าอะไรและคิดเงินเท่าไหร่ (หลักฐานอยู่ในชีต TS-14 เอง:
-- ตัวอย่าง `TSK-14 6x200+150-BU` คิด 4000+(3*300)+(1*130)=5,030 โดยไม่มีบรรทัดไหนคิดค่า -BU)
-- ⇒ ความหมายอยู่ในหัวคนออกใบ ตารางนี้คือที่ให้เขาพิมพ์มันลงมา
--
-- ทำไมเก็บทั้งแถวเป็น jsonb ไม่แตกเป็นคอลัมน์ละช่อง:
--   รูปของ SubCode (services/pricingLab/types.ts) ยังขยับได้ตลอดจนกว่าดีไซน์จะนิ่ง — แตกเป็น
--   คอลัมน์แปลว่าทุกครั้งที่เพิ่มช่องต้องมี migration ตามอีกไฟล์ ซึ่งเป็นสิ่งที่เจ้าของสั่งไว้เองว่า
--   ต้อง "ปรับแก้เพิ่มเติมยังไงก็ได้" · แบบเดียวกับ quotations.rule_overrides / messages.meta
--   ฝั่งอ่านตรวจรูปให้อยู่แล้วที่ db/pricingLabRepo.ts ที่เดียว
--
-- sub_code / scope เป็น GENERATED ไม่ใช่คอลัมน์ที่แอปเขียนเอง — เพราะถ้าแอปเขียนสองที่
-- (ทั้งใน data และในคอลัมน์) วันหนึ่งมันจะไม่ตรงกัน แล้วแถวจะหายไปจากการค้นทั้งที่ยังอยู่ในตาราง
--
-- scope = ขอบเขตว่ารหัสย่อยนี้ใช้กับรุ่นไหน: ชื่อรุ่น/ชื่อเรียกอื่น · `TS*` ทั้งตระกูล · `*` ทุกรุ่น
--   ค่าเริ่มต้นบนหน้าจอคือ "รุ่นเดียว" เสมอ เพราะของจริงมีตัวอักษรเดียวกันที่คนละรุ่นคิดคนละราคา
--   (หน้าแปลน JIS 10K 1 นิ้ว: ชีต TS-18 คิด 650 · ชีต TW คิด 800)
--
-- UNIQUE (sub_code, scope) — หนึ่งตัวอักษรต่อหนึ่งขอบเขต มีได้แถวเดียว การตั้งซ้ำคือการแก้ของเดิม
--   ไม่ใช่การเพิ่มแถวที่สอง (ถ้ามีสองแถว ลำดับการค้นใน subcodes.ts จะเลือกตัวไหนก็ได้ = ราคาสุ่ม)
--   แต่ `S000` (ตรงตัว) กับ `S###` (แม่แบบ) เป็นคนละ sub_code ⇒ อยู่ด้วยกันได้ และ
--   ลำดับ "ตรงตัวชนะแม่แบบ · แคบชนะกว้าง" ตัดสินให้เองใน findSubCode()

CREATE TABLE IF NOT EXISTS pricing_subcodes (
  id         BIGSERIAL PRIMARY KEY,
  data       JSONB       NOT NULL,
  sub_code   TEXT        GENERATED ALWAYS AS (data->>'subCode') STORED,
  scope      TEXT        GENERATED ALWAYS AS (data->>'scope')   STORED,
  created_by TEXT,                                    -- username ของแอดมินที่ตั้ง (ไม่ใช่ FK — โมดูลนี้ต้องถอดออกได้)
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS pricing_subcodes_code_scope_idx
  ON pricing_subcodes (sub_code, scope);
