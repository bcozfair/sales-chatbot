--    และเป็นตัวที่ทำให้ไฟล์นี้ขึ้น prod ล่วงหน้าก่อนโค้ดได้โดยไม่มีอะไรเปลี่ยน
ALTER TABLE public.quotations ADD COLUMN IF NOT EXISTS customer_sales_team text;

