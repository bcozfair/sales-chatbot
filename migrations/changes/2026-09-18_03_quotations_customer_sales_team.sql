--   ค่าว่าง  = ผู้ติดต่อคนนั้นไม่มีทีมขายในฐานจริง (มี 9 ใบจาก 1,931 ใบบนฐาน dev วัด 2026-09-18)
--             ⇒ เก็บเป็น NULL เหมือนกัน ไม่เดาค่าแทน ตามกติกาเดิมของช่องนี้ที่ห้ามถอยไปใช้
--             สังกัดของเซลล์ผู้ออกใบ (เหตุผลเต็มอยู่ที่หัว ODOO_EXPORT_SALES_TEAM_JOIN)
--
-- ⚠️ ไฟล์นี้ + โค้ดของเฟส H เปลี่ยนพฤติกรรมของ **ใบที่ออกจาก LINE ด้วย** โดยตั้งใจ — เป็นข้อยกเว้น
--    ข้อเดียวของกติกา "แยกโหมดด้วย user_id = web:%" เพราะไฟล์ export เป็นของร่วมกันทั้งสองทางเข้า
