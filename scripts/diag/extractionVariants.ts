/** ใส่ variant ลง prompt — ยืนยันว่าแทนที่ได้จริงทุกคู่ ไม่งั้นโยนทิ้ง */
export function applyVariant(name: string, prompt: string): string {
  const v = VARIANTS[name];
  if (!v) throw new Error(`ไม่รู้จัก variant "${name}"`);
  let out = prompt;
  for (const [find, replace] of v.patches) {
    if (!out.includes(find)) {
      throw new Error(`variant "${name}": หาข้อความเป้าหมายใน prompt ไม่เจอ — prompt ของ production เปลี่ยนไปแล้ว ต้องอัปเดต extractionVariants.ts ก่อนวัดต่อ\nข้อความที่หา: ${find.slice(0, 80)}…`);
    }
    out = out.replace(find, replace);
  }
  if (out === prompt) throw new Error(`variant "${name}": patch ไม่เปลี่ยนอะไรเลย`);
  return out;
}
