/** จำนวนเงิน หน่วยบาท */
export type Money = number;

/** สเปกที่ผู้ใช้เลือก — input ของ engine */
export interface ProductConfig {
  /** รหัสตระกูลรุ่น เช่น 'TS-04' · 'BH-01C' (รับ alias ได้) */
  model: string;
  /** ค่าแกนที่เป็นตัวเลือกแบบจำกัด เช่น { D: '6', thread: '1/2”' } — ค่าเป็น string ดิบจากชีต */
  axes?: Record<string, string>;
  /** ค่าที่เป็นตัวเลขต่อเนื่อง เช่น { L1: 300, L2: 150, cable_m: 3 } */
  dims?: Record<string, number>;
  /** ตัวเลือกแบบติ๊ก เช่น ['head:blacklite_l', 'bend:L'] */
  options?: string[];
  /**
   * ตัวอักษรท้ายเลขรุ่นที่ลูกค้าสั่ง เช่น 'C' ของ `BH-02C` — ต้องตรงกับ `model.variant.suffix`
   * ไม่ตรง/ไม่ใส่ = คิดเป็นรุ่นหลักเปล่า ๆ · `parseProductCode` เติมช่องนี้ให้เองจากรหัส
   */
  variant?: string;
  /**
   * แกนที่ **รหัสบอกมาแล้วแต่ตัวอ่านยังอ่านไม่ออก** (แกน → ข้อความในรหัส) เช่น `{ cable: 'TU' }`
   * ของ `+2MTU` · engine **ห้ามเติมค่าเริ่มต้นให้แกนนี้** — เคยเกือบหลุด (2026-09-24 ก่อนลงฐาน):
   * `TSK-01(M6)4.8+2MT` (สายเทปล่อน 180/ม.) ได้ค่าสายสแตนเลสถัก 80 พร้อมคำอธิบายว่า "รหัสไม่ได้ระบุ"
   */
  unread?: Record<string, string>;
}

// ── เงื่อนไข ─────────────────────────────────────────────────────────────────

/**
 * เงื่อนไขแบบประกาศ — ตั้งใจให้เล็กและปิด ไม่ใช่ภาษาสคริปต์
 * เพราะสมุดราคาถูกแก้โดยแอดมิน การเปิดให้เขียน expression อิสระคือการเปิดช่องให้
 * คนตั้งราคาเขียนโค้ดลงฐานข้อมูลโดยไม่มีใครรีวิว
 */
export type Predicate =
  | { always: true }
  | { axis: string; in: string[] }
  | { axis: string; notIn: string[] }
  | { option: string }
  | { dim: string; gt?: number; gte?: number; lt?: number; lte?: number }
  | { all: Predicate[] }
  | { any: Predicate[] }
  | { not: Predicate };

// ── ค่าที่คำนวณมาจากค่าอื่น ───────────────────────────────────────────────────

/**
 * ค่าที่ไม่ได้กรอกเข้ามาตรง ๆ แต่คำนวณจาก dims อื่น แล้วเขียนกลับเข้า dims
 * ให้ constraint / adder มองเห็นได้
 *
 * ค่าคงที่ของสูตรอยู่ใน `consts` ไม่ใช่ในโค้ด — เช่น BH ใช้ π = **3.14** (ไม่ใช่ Math.PI)
 * และ 645 (mm² ต่อ 1 ตารางนิ้ว) ทั้งสองค่าเขียนอยู่ในชีต ถ้าวันหนึ่งเขาเปลี่ยนตัวหาร
 * จะได้แก้ที่สมุดราคา ไม่ใช่มาไล่หาใน engine
 */
export interface DerivedDim {
  /** ชื่อที่จะถูกเขียนลง dims */
  name: string;
  label: string;
  formula: 'sum' | 'cylinderAreaIn2';
  /** ชื่อ dims ที่เป็น input */
  args: string[];
  consts?: Record<string, number>;
  round?: RoundMode;
}

export type RoundMode = 'ceil' | 'floor' | 'exact';

// ── ฐานราคา ─────────────────────────────────────────────────────────────────

/** ช่วงค่าหนึ่งแถบ — `flat` = ราคาเหมาทั้งช่วง · `rate` = ต่อหนึ่งหน่วยของปริมาณนั้น */
export interface Band {
  min: number;
  /** null = ไม่มีขอบบน */
  max: number | null;
  flat?: Money;
  rate?: Money;
  label?: string;
}

export type BaseSpec =
  /**
   * ตารางค้นหาตามแกน — **แถวที่ไม่มี = ไม่รับผลิต ไม่ใช่ราคา 0**
   * ชีตจริงเบาบางมากโดยตั้งใจ (TS-04: D=2 มีครบ 6 ขนาดเกลียว แต่ D=19 มีแค่ 2)
   */
  | { kind: 'matrix'; axes: string[]; cells: Record<string, Money> }
  /** แถบราคาตามปริมาณ (ใช้กับ BH ที่คิดจากพื้นที่ผิว) */
  | { kind: 'banded'; quantity: string; bands: Band[] }
  /** ฐานของรุ่นนี้ = ฐานของอีกรุ่น (เช่น BH-01C ใช้ฐานของ BH-01 แล้วค่อย +20% ด้วย adder) */
  | { kind: 'ref'; model: string };

// ── ส่วนที่บวกเพิ่ม ──────────────────────────────────────────────────────────

/**
 * `order` มีอยู่เพราะลำดับมีผลจริง — ตัวอย่างในชีต BH:
 *   10,975 → +20% = 13,170 → +320 = 13,490
 * ถ้าสลับเป็น (10,975+320) × 1.2 = 13,554 ผิดไป 64 บาท
 */
export interface Adder {
  id: string;
  label: string;
  order: number;
  when?: Predicate;
  kind: 'flat' | 'percent' | 'perUnit';

  /** flat: จำนวนคงที่ */
  amount?: Money;

  /** percent: คิดจากยอดสะสม ณ ลำดับนั้น */
  percent?: number;

  /** perUnit: คิดจากส่วนที่เกิน baseline */
  dim?: string;
  /** ส่วนที่เกินค่านี้จึงคิดเงิน — ไม่ระบุ = ใช้ standard[dim] ?? 0 */
  over?: number;
  step?: number;
  round?: RoundMode;
  /** ตัวคูณ เช่น สายของ BH คิด ×2 เพราะใช้ 2 เส้น */
  times?: number;

  /** ราคาเดียวทุกกรณี */
  rate?: Money;
  /** ราคาต่างกันตามค่าแกน (เช่น "บวกเพิ่ม 100 mm ละ" ของ TS-04 ต่างกันตาม D) */
  byAxis?: string;
  rates?: Record<string, Money>;
  /**
   * true = ถ้าไม่มีราคาสำหรับค่าแกนนี้ ให้ข้ามเงียบ ๆ
   * false/ไม่ระบุ = ถือเป็น "ทำไม่ได้" (ชีตเว้นว่างไว้แปลว่าไม่รับทำ)
   */
  skipIfNoRate?: boolean;
  /** หน่วยที่จะพิมพ์ใน breakdown เช่น 'mm' · 'm' */
  unit?: string;
  /** ที่มาในชีต เช่น "TS-14!A19" — ไว้ตามกลับไปตรวจเวลาราคาเพี้ยน */
  source?: string;

  // ── สามช่องข้างล่างนี้มีไว้ให้ "คนตั้งราคา" ไม่ใช่ให้ importer ──────────────
  /**
   * ปิดกฎไว้ชั่วคราวโดยไม่ต้องลบ — ลบแล้วประวัติหาย และกฎที่เคยใช้ก็ตามกลับไม่ได้ว่า
   * เมื่อก่อนคิดเท่าไหร่ ⇒ โปรโมชันที่ "หยุดไว้ก่อน" ต้องเป็นการปิด ไม่ใช่การลบ
   */
  disabled?: boolean;
  /** กฎที่คนเพิ่มเองทีหลัง ไม่ได้มาจากไฟล์ราคา — ต้องแยกให้เห็นเวลาสมุดราคารอบใหม่มา */
  custom?: boolean;
  /** เหตุผลที่คนตั้งกฎเขียนไว้เอง (ต่างจาก `source` ที่เป็นที่มาในชีต) */
  note?: string;
}

// ── รหัสย่อยในรหัสสินค้า ─────────────────────────────────────────────────────

/**
 * ผลของรหัสย่อยหนึ่งตัวต่อราคา — หกแบบนี้ครอบคลุมของจริงที่เจอในไฟล์ราคาทั้งสองไฟล์
 * (ไล่ครบทั้ง 30 ชีตเมื่อ 2026-09-18) และ **ห้ามมีแบบที่เจ็ดที่แปลว่า "เดาเอา"**
 *
 *   none       อ่านออก บันทึกไว้ แต่ไม่คิดเงิน  — เช่น แรงดันไฟ 240 ของ BH
 *   basePrice  ทิ้งราคาตั้งจากตาราง ใช้ราคานี้แทน — รุ่นพิเศษที่ราคาไม่อิงตาราง
 *   flat       บวกเงินคงที่
 *   percent    บวกเป็นเปอร์เซ็นต์ของยอดสะสม ณ ลำดับนั้น
 *   perUnit    บวกตามส่วนที่เกินมาตรฐาน (ใช้ช่องชุดเดียวกับ Adder ทุกช่อง)
 *   setAxis    เซ็ตค่าแกนแล้วให้ตารางราคาเดิมคิดต่อ — เช่น (F5) = หน้าแปลน 5 นิ้ว
 */
export type SubCodeEffect = 'none' | 'basePrice' | 'flat' | 'percent' | 'perUnit' | 'setAxis';

/**
 * หนึ่งแถวในตารางรหัสย่อย = "ตัวอักษรท่อนนี้ในรหัส แปลว่าอะไร และทำอะไรกับราคา"
 *
 * **ทำไมไม่ผูกกับรุ่นเดียวเสมอ:** คำเดียวกันข้ามรุ่นราคาไม่เท่ากันจริง (หน้าแปลน JIS 10K
 * ขนาด 1": ชีต TS-18 = 650 · ชีต TW = 800) แต่บางคำก็ใช้ร่วมกันทุกรุ่นจริง ๆ
 * ⇒ มี `scope` สามชั้น และชั้นแคบชนะชั้นกว้างเสมอ (ดู `subcodes.ts`)
 */
export interface SubCode {
  /** ท่อนตามที่พิมพ์ในรหัส เช่น 'BU' · 'MP' · 'S###' */
  subCode: string;
  /** 'exact' = ตรงตัว · 'pattern' = แม่แบบ โดย # แทนตัวเลขหนึ่งหลัก (S### จับ S000–S999) */
  match: 'exact' | 'pattern';
  /** รหัสรุ่น · 'TS-18*' (ทั้งตระกูล) · '*' (ทุกรุ่น) */
  scope: string;
  /** ข้อความไทยที่จะขึ้นบนจอ — คนอ่านใบต้องเข้าใจโดยไม่ต้องเปิดตาราง */
  reads: string;
  effect: SubCodeEffect;
  /** ลำดับการคิด เหมือนกฎบวกเพิ่ม (ลำดับมีผลจริงเมื่อมีเปอร์เซ็นต์) — ไม่ใส่ = 50 */
  order?: number;

  /** flat · basePrice */
  amount?: Money;
  /** percent */
  percent?: number;

  // perUnit — ช่องชุดเดียวกับ Adder เป๊ะ เพื่อให้คิดด้วยโค้ดเดียวกัน ไม่ใช่สูตรที่สอง
  dim?: string;
  over?: number;
  step?: number;
  round?: RoundMode;
  rate?: Money;
  times?: number;
  unit?: string;

  // setAxis
  axis?: string;
  value?: string;

  /** ปิดไว้ชั่วคราวโดยไม่ลบ — เหตุผลเดียวกับ `Adder.disabled` */
  disabled?: boolean;
  /** true = คนตั้งค่าเองทีหลัง ไม่ได้มาจากไฟล์ราคา ⇒ ไฟล์ราคารอบใหม่ต้องไม่ทับทิ้ง */
  custom?: boolean;
  /** ที่มาในชีต เช่น "TS-14!A10" */
  source?: string;
  /** ใครตั้งค่า / เมื่อไหร่ — ไว้ตอบตอนราคาเพี้ยนว่า "ใครใส่ค่านี้" */
  by?: string;
  at?: string;
  note?: string;
}

// ── กฎที่ไม่ใช่ราคา ──────────────────────────────────────────────────────────

/**
 * `quoteOnRequest` ไม่ใช่ error และไม่ใช่ราคา 0 — ชีตเขียนไว้ตรง ๆ หลายที่ว่า
 * "หน้าแปลนนอกเหนือจากนี้ให้ขอราคาจากผลิต 2" / "2 Element ให้ปรึกษาผลิต 2 ก่อน"
 */
export interface Constraint {
  id: string;
  when: Predicate;
  level: 'block' | 'quoteOnRequest' | 'warn';
  message: string;
  /** ที่มาในชีต เช่น "TS-14!A19" — ไว้ตามกลับไปตรวจเวลาเถียงกันว่ากฎนี้มาจากไหน */
  source?: string;
  /** ปิดไว้ชั่วคราว — เหตุผลเดียวกับ `Adder.disabled` */
  disabled?: boolean;
  custom?: boolean;
  note?: string;
}

// ── ตัวเลือกท้ายรหัส ─────────────────────────────────────────────────────────

/**
 * ตัวอักษรต่อท้าย **เลขรุ่น** ที่ไม่ได้เปลี่ยนตารางราคา แค่คิดเพิ่มจากรุ่นหลัก
 * ตัวอย่างเดียวที่มีวันนี้คือตัว **C** ของซีรีส์ BH
 *
 * **ทำไมไม่เป็นรุ่นแยก** (เจ้าของเคาะ 2026-09-22 · แก้จริง 2026-09-23):
 * ชีตต้นฉบับวาง C เป็น **คอลัมน์ถัดจาก BH-01 ในตารางเดียวกัน** (`Sheet1!C1:C9` มีเซลล์
 * `C3:C9` ผสานกันเขียนว่า "บวกเพิ่มจากราคา BH-01 อีก 20%") ไม่ใช่ตารางของตัวเอง
 * พอสมุดราคาแตกมันเป็นรุ่น `BH-01C` ต่างหาก รหัสที่ขายจริงอีกสองตัวก็ไม่มีรุ่นรองรับ:
 * `BH-02C` (11 รายการ) กับ `BH-03C` (1 รายการ) ตกไปคิดเป็นรุ่นฐานเปล่า ๆ **ไม่บวก 20%
 * และไม่มีอะไรฟ้อง** — `parseProductCode` เห็นตัว C เป็นตัวอักษรที่อ่านไม่ออก แต่ยัง
 * คืนราคาออกมาหน้าตาปกติ (วัดจากแค็ตตาล็อกจริง 2026-09-22)
 * ⇒ ย้าย C มาเป็น "ตัวเลือกของรุ่นหลัก" ตั้งที่เดียวครอบทุกรหัสที่ลงท้ายด้วยตัวนั้น
 *
 * **ไม่ใช่ "+20% กับทุกอย่าง"** — ชีตเขียนไว้ชัดว่าของแถมสี่อย่างคูณสอง
 * (`conn_pl2` 160→320 · `term_10a` 80→160 · `term_30a` 150→300 · `nut` 85→170)
 * ส่วนค่าสาย/ท่อ/Hold คิดเท่ารุ่นปกติ ⇒ ต้องเก็บเป็น "ราคาฝั่งตัวเลือก รายรายการ"
 * ไม่ใช่ตัวคูณตัวเดียว
 */
export interface ModelVariant {
  /** ตัวอักษรที่ต่อท้ายเลขรุ่น เช่น 'C' (เทียบแบบไม่สนตัวพิมพ์) */
  suffix: string;
  /** ชื่อที่ขึ้นบนจอและในที่มาของราคา เช่น "รุ่น C" */
  label: string;
  /**
   * บวกเพิ่มจากยอดสะสม ณ ลำดับ `order` กี่เปอร์เซ็นต์
   * **0 = ไม่บวกเพิ่ม** ซึ่งต่างจาก `disabled` ตรงที่ราคาของแถมฝั่งนี้ยังใช้อยู่
   */
  percent?: number;
  /**
   * ลำดับที่บวกเปอร์เซ็นต์ — ต้องอยู่ **หลังราคาตั้ง ก่อนของแถม** ตามที่ชีตทำ
   * ตัวอย่างในชีต BH: 10,975 → +20% = 13,170 → +320 = 13,490
   * สลับเป็น (10,975+320) × 1.2 = 13,554 ผิดไป 64 บาท ⇒ ไม่ใส่ = 10
   */
  order?: number;
  /**
   * ราคาของกฎบวกเพิ่มที่ **ไม่เท่ารุ่นหลัก** — `id ของกฎ → ราคาฝั่งตัวเลือกนี้`
   * กฎที่ไม่มีชื่ออยู่ในนี้คิดเท่ารุ่นหลักทุกบาท ⇒ "ไม่มีในตาราง" กับ "เท่าเดิม" เป็นเรื่องเดียวกัน
   * ตัวเลขทับเฉพาะช่องราคา (`amount`/`rate`/`percent` ตามชนิดของกฎ) **ไม่แตะเงื่อนไขและลำดับ**
   */
  adderPrices?: Record<string, Money>;
  /** ปิดไว้ = รหัสที่ลงท้ายด้วยตัวอักษรนี้กลับไปคิดเป็นรุ่นหลักเปล่า ๆ (ไม่ใช่หาราคาไม่เจอ) */
  disabled?: boolean;
  /**
   * false = ตัวเลขชุดนี้ยังไม่ได้ผ่านฝ่ายขาย (ลอกรูปมาจากรุ่นพี่) — หน้าจอต้องติดป้ายไว้
   * ตัวอย่าง: ชีตไม่เคยเขียนว่า BH-03C คิดเพิ่มเท่าไหร่ แต่ของขายจริงมี 1 รายการ
   */
  confirmed?: boolean;
  /** ที่มาในชีต เช่น "Sheet1!C1:C9" */
  source?: string;
  custom?: boolean;
  note?: string;
  by?: string;
  at?: string;
}

/** ดู `PriceModel.axisDefaultsBy` */
export interface AxisDefaultBy {
  /** หัวคอลัมน์ในชีต เช่น "ชนิดสาย รุ่นเริ่มต้น" — หน้าสมุดรายชีตใช้เป็นหัวคอลัมน์ */
  label?: string;
  /** แกนที่เป็นตัวตัดสิน เช่น 'sensor' */
  by: string;
  /** ค่าของแกน `by` → ค่าที่เติมให้ */
  values: Record<string, string>;
  /** ที่มาในชีต เช่น "TS-01+TS-01-0!G11:G15" */
  source?: string;
}

// ── หน้าตาของชีตต้นฉบับ ───────────────────────────────────────────────────────

/**
 * ของที่ชีต Excel เขียน/ระบายไว้รอบตารางราคาตั้ง **เพื่อให้คนอ่าน** — engine ไม่อ่านช่องนี้เลย
 * มีไว้ให้หน้าสมุดรายชีตวางได้เหมือนไฟล์ (เจ้าของสั่ง 2026-09-24 "ต้องการสามอย่างนี้ด้วย")
 * ตัวอย่างทั้งสามอย่างจากชีต `TS-01+TS-01-0`:
 *   · `rowNote`       คอลัมน์ G "ชนิดสาย รุ่นเริ่มต้น" — TSK/TSJ = สายถักสแตนเลส · TST = เทปล่อน · ที่เหลือ PVC
 *   · `colNotes`      ตัวหนังสือแดงใต้ตาราง `*M8x1.25` (ใต้ M8x1.0) · `*M10x1.5` (ใต้ M10x1.25)
 *                     = พิตช์อีกแบบที่ใช้ราคาเดียวกัน (ตัวอ่านรหัสรู้อยู่แล้ว ดู code.ts — ตรงนี้แค่แสดง)
 *   · `highlightCols` คอลัมน์ที่ระบายเหลืองทั้งคอลัมน์ (1/4” ของ TS-01 · M5 ของ TS-01-0)
 * **ห้ามให้ราคาขึ้นกับช่องนี้** — ข้อความที่มีผลกับราคาต้องเป็นข้อมูลที่ engine อ่าน ไม่ใช่ข้อความประกอบ
 * (เกิดแล้ว 2026-09-24: "ชนิดสาย รุ่นเริ่มต้น" ของ TS-01 เจ้าของยืนยันว่ามีผลกับราคา ⇒ ย้ายไป `axisDefaultsBy`
 *  และ `rowNote` ของสองรุ่นนั้นถูกถอดออก — `rowNote` เหลือไว้สำหรับข้อความที่เป็นแค่คำอธิบายจริง ๆ)
 */
export interface SheetLayout {
  /** คอลัมน์ข้อความท้ายตาราง: หัวคอลัมน์ + ข้อความของแต่ละแถว (คีย์ = ค่าแกนแถว) */
  rowNote?: { label: string; values: Record<string, string> };
  /** ข้อความใต้คอลัมน์ (คีย์ = ค่าแกนคอลัมน์) */
  colNotes?: Record<string, string>;
  /** ค่าแกนคอลัมน์ที่ชีตระบายเหลือง */
  highlightCols?: string[];
}

// ── สมุดราคา ─────────────────────────────────────────────────────────────────

export interface PriceModel {
  code: string;
  label: string;
  /** ชีตต้นทาง — ไว้ตามกลับไปหาที่มาเวลาราคาเพี้ยน */
  sheet?: string;
  /** รหัสรุ่นอื่นที่ใช้ตารางเดียวกัน (BH-02 ใช้ของ BH-01 · TSJ-04 ใช้ของ TSK-04) */
  aliases?: string[];
  /**
   * สเปกที่ "รวมอยู่ในราคาตั้งแล้ว" — ทุกชีตประกาศไว้ที่หัวตาราง
   * เช่น TS-04 เขียนว่า "ราคาตั้ง Standard TS_-04(S_) 6x100+1M" ⇒ { L1: 100, cable_m: 1 }
   * ถ้าไม่เก็บค่านี้ จะไม่รู้ว่าจะคิดส่วนต่างจากอะไร
   */
  standard: Record<string, number>;
  /**
   * ค่าเริ่มต้นของแกนที่ "มีค่ามาตรฐานอยู่แล้ว ถ้าไม่ได้ระบุ" — ต่างจาก `standard` ตรงที่
   * นั่นเป็นปริมาณ (ตัวเลข) ส่วนนี่เป็นตัวเลือก (ข้อความ)
   * ตัวอย่างเดียวที่มีวันนี้: ชนิดสายของ TS-04 — ชีตประกาศไว้เองที่ `TS-02,02-SI!E25`
   * ว่า "สาย Standard Type K = สแตนเลสถัก" ⇒ รหัสที่เขียนแค่ `+3M` ไม่ได้บอกชนิดสาย
   * ต้องคิดด้วยสายมาตรฐาน ไม่ใช่ตกไปเป็น "ไม่มีราคา"
   * **ไม่มีผลกับแกนของตารางราคาตั้ง** (matrix) ซึ่งต้องเลือกเองเสมอ
   */
  axisDefaults?: Record<string, string>;
  /**
   * ค่าเริ่มต้นของแกนที่ **ขึ้นกับค่าของอีกแกน** — ใช้เมื่อรหัสไม่ได้บอกแกนนั้นเอง
   * ตัวอย่างเดียววันนี้: ชีต `TS-01+TS-01-0` คอลัมน์ G "ชนิดสาย รุ่นเริ่มต้น" — ชนิดสายผูกกับ TYPE
   * (TSK/TSJ = สแตนเลสถัก · TST = เทปล่อน · TSP/TSPA/TSZ = PVC) ⇒ `{ cable: { by: 'sensor', values: {...} } }`
   * เจ้าของยืนยัน 2026-09-24: "มันก็บอกอยู่แล้วนี้ไงครับ เรื่องสาย" — เดิมเก็บเป็นข้อความประกอบ (`layout.rowNote`)
   * ทำให้รหัสที่สายเกิน 1 เมตรคิดไม่ได้ทั้งหมด (929 จาก 1,214 รหัสจริงของ TS-01/TS-01-0)
   * ลำดับความสำคัญ: ค่าที่รหัสบอกเอง > ช่องนี้ > `axisDefaults` · ค่าต้องเป็นคีย์ที่กฎราคาใช้จริง (เช่นคีย์ของ `rates`)
   */
  axisDefaultsBy?: Record<string, AxisDefaultBy>;
  derivedDims?: DerivedDim[];
  base: BaseSpec;
  adders: Adder[];
  constraints: Constraint[];
  /** ตัวอักษรท้ายเลขรุ่นที่คิดเพิ่มจากรุ่นนี้ (ซีรีส์ BH = ตัว C) — ดู `ModelVariant` */
  variant?: ModelVariant;
  /** หน้าตาของชีตต้นฉบับรอบตารางราคาตั้ง — แสดงผลอย่างเดียว ดู `SheetLayout` */
  layout?: SheetLayout;
  /**
   * สถิติตอนนำเข้า ติดมากับสมุดราคาเพื่อให้ผู้อ่านไม่ต้องนับเอง
   * จำเป็นเพราะ **นับจากคีย์ของ `cells` ให้ผลผิด**: แถวที่ว่างทั้งแถว (D = "7TN" ของ TS-04)
   * ไม่โผล่ในคีย์สักตัว นับเองได้ช่องว่าง 46 ขณะที่ของจริง 52 (วัด 2026-09-17)
   */
  importStats?: {
    code: string;
    sheet: string;
    baseCells: number;
    emptyCells: number;
    adderRates: number;
    floatNoiseFixed: number;
  };
}

export interface PriceBook {
  version: string;
  source: string;
  models: Record<string, PriceModel>;
  /**
   * ตารางรหัสย่อย — อยู่ระดับสมุด ไม่ใช่ระดับรุ่น เพราะหนึ่งแถวใช้ข้ามรุ่นได้
   * (ช่อง `scope` ของแต่ละแถวเป็นตัวบอกเองว่าครอบถึงไหน)
   */
  subCodes?: SubCode[];
  /**
   * ติดมาเมื่อสมุดราคาถูกแก้โดยคน (ผ่านหน้าแก้กฎ หรือผ่านไฟล์ .xlsx ที่ส่งออกไปแก้แล้วนำกลับเข้ามา)
   * **ไม่มีค่านี้ = ของที่แปลงจากไฟล์ราคาตรง ๆ ยังไม่มีใครแตะ** — ต้องแยกให้ออก เพราะเวลาราคา
   * ที่ลูกค้าได้ไม่ตรงกับที่ฝ่ายขายคิด คำถามแรกคือ "ใครแก้ เมื่อไหร่"
   */
  edited?: { at: string; by?: string; note?: string };
}

