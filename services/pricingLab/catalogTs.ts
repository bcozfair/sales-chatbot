import type { CatalogOption } from './catalogBh.js';

export type TsFamily = 'TS_-01' | 'TS_-01-0' | 'TS_-02' | 'TS_-02-SI' | 'TS_-03' | 'TS_-04' | 'TS_-05' | 'TS_-06' | 'TS_-07' | 'TS_-08' | 'TS_-09' | 'TS_-10' | 'TS_-11' | 'TS_-12' | 'TS_-12R' | 'TS_-14' | 'TS_-18';

export interface TsSlot {
  label: string;
  kind: 'choice' | 'number';
  options?: CatalogOption[];
  /** ตัวเลือกที่ขึ้นกับช่อง "ชนิดหัววัด" (TS / N / P) — TS_-03 · 04 · 06 · 11 */
  optionsByProbe?: Record<string, CatalogOption[]>;
  unit?: string;
  /** ค่าที่แคตตาล็อกเขียนว่า Standard — โชว์เป็นตัวจางในช่องว่าง */
  placeholder?: string;
  hint?: string;
  /** ช่องตัวเลขที่เว้นว่างได้ (ไม่เขียนลงรหัส = ค่ามาตรฐาน) */
  optional?: boolean;
  /**
   * ค่ามาตรฐานของตัวเลือก `''` ตามที่คนเขียนลงรหัส (`M5` ของ TS_-01-0 · `1/4` ของ TS_-01) — รหัสจริงที่เขียนค่ามาตรฐานออกมา
   * (`TSP-01-0(M5)+3MTU` · 28 รหัส) ได้ตัวเลือกมาตรฐาน ไม่ใช่ "นอกแคตตาล็อก"
   */
  stdCode?: string;
}

/** `slot` = ช่อง · `sep` = ตัวคั่นที่วาดตามแผนผังแคตตาล็อก (`' '` = เว้นวรรคที่รหัสจริงเขียน) · `fixed` = ตัวอักษรตายตัว */
export type TsLayoutItem = { slot: string } | { sep: string } | { fixed: string };

export interface TsFamilySpec {
  family: TsFamily;
  /** ชื่อบนช่อง "รุ่น" ตามหัวหน้าแคตตาล็อก */
  head: string;
  /** คำในรายการของช่อง "รุ่น" — ชนิดเซนเซอร์บนหัวหน้า + คำในภาพประกอบ (แคตตาล็อก TS ไม่มีชื่อรุ่นแบบ BH) */
  name: string;
  /** รุ่นในสมุดราคาที่ตารางนี้คิดราคา (รหัสในฐาน — ประวัติราคาผูกกับชื่อนี้) */
  model: string;
  /**
   * ตารางของแคตตาล็อกที่ใช้รุ่นในสมุดราคาร่วมกับตารางอื่น — ค่าของแกน `submodel` ของรุ่นนั้นที่ตารางนี้คิด
   * (TS_-02-SI = คอลัมน์ `TS-02-SI` ของ `TSK-02` · แคตตาล็อกคนละหน้ากับ TS_-02 · เจ้าของส่งมา 2026-10-05) —
   * ไม่มี = ตารางหลักของรุ่น (รหัสที่ไม่บอกรุ่นย่อย) · ใช้ที่ `tsFamilyOfModel` ตัวเดียว
   */
  submodel?: string;
  layout: TsLayoutItem[];
  slots: Record<string, TsSlot>;
  /** ค่าเริ่มต้นตอนสลับมารุ่นนี้ — รหัสจริงที่พบบ่อยของตารางนั้น */
  defaults: Record<string, string>;
  /** บวกเพิ่มที่ชีตมีราคาแต่แคตตาล็อก/รหัสไม่มีท่อนนี้ (หัก L · หักฉาก — ข้อ 8) · `code` = option ของกฎในสมุดราคา */
  addons?: CatalogOption[];
  /**
   * ช่องที่ **ค่านอกแคตตาล็อก = ต้องขอราคาจากฝ่ายผลิต** และแอดมินเพิ่มค่านั้นเป็นช่องในตารางของชีตได้เองจากหน้าสมุดราคา
   * (ช่องของแคตตาล็อก → แกนในสมุดราคา) — เจ้าของสั่ง 2026-09-29 (TS_-01 ก่อน · เคาะ mockup `ts01-ask-price` แบบ A):
   * *"ทุกข้อที่ต้องขอราคาจากฝ่ายผลิต ต้องมี ui รองรับให้สามารถเอาราคามาใส่ได้ภายหลังเองได้โดยไม่ต้องมาแก้โค้ดอีก"*
   *   · `sensor` — หัวรหัสที่ไม่อยู่ในรายการ (`TSE-01`) ได้รุ่นนี้ แต่คิดได้จาก **แถวของตัวเองเท่านั้น** (ไม่ยืมแถวอื่น)
   *   · `thread` — เกลียวที่ไม่อยู่ในรายการ (M12 · S1–S4 · 1/8) = คอลัมน์ของตัวเอง · ไม่แปลง "หุน" เป็นเกลียวนิ้ว
   *     (`S2` = 1/4” **NPT** ไม่ใช่ 1/4” ของตาราง — เจ้าของเคาะ B#7)
   *   · `d` — ขนาดแกนที่ไม่อยู่ในรายการ ใช้อัตราความยาวแกนของ **ขนาดถัดขึ้นไปที่มีอัตรา** (4 → 4.8 · 5 → 6 · เจ้าของเคาะ B#2)
   *     ใหญ่กว่าทุกขนาดที่มีอัตรา = ขอราคา · แอดมินเพิ่มขนาดใหม่พร้อมอัตรา = ราคาตั้งของคอลัมน์เกลียว + อัตราใหม่
   *     **ตารางที่ขนาดแกนเป็นแถวของตารางราคาตั้งเอง** (TS_-02 · เจ้าของสั่ง 2026-10-05) ไม่ปัดขึ้น — ราคาตั้งต่างกันทุกขนาด ⇒
   *     ขนาด (+ ตัวอักษรวัสดุในรายการ เช่น `2.5A`) ที่ตารางไม่มี = แถวของตัวเอง "ต้องขอราคา" · แอดมินเพิ่มแถวแล้วกรอก = คิดได้ + เตือน
   * ไม่มีช่องนี้ = รุ่นนั้นใช้กติกาเดิมทุกอย่าง (ค่าที่ตารางไม่มี = อ่านไม่ออก)
   * คีย์ `thread` = **ช่องเกลียวของตารางนั้น** ซึ่ง TS_-01-0 ชื่อ `hold` (Hold Size · 2026-10-05) — ชื่อช่องจริงถามที่ `askSlotKey`
   */
  askPrice?: { sensor?: string; thread?: string; d?: string };
  /**
   * ขนาดแกน → เกลียวที่แคตตาล็อกจับคู่ไว้ (ค่าในรายการของช่อง) — ไม่คู่ = **เตือน ไม่บล็อก** และคิดราคาตามแกนในรหัส
   * (เจ้าของเคาะ B#8 2026-09-29: ราคาตั้งไม่ขึ้นกับแกน · Odoo ขาย `TSK-01(M6)5x50+1M` ที่ 160 + อัตราแกน 6)
   */
  dThreads?: Record<string, string[]>;
  /**
   * วงเล็บของตารางนี้คือ **ขนาดเขี้ยวล็อค (Connector ID)** ไม่ใช่เกลียว (TS_-02) — ชีต `TS-02,02-SI` คิดราคาตามขนาดแกนอย่างเดียว
   * (คอลัมน์ B "ขนาดเขี้ยวล็อค ID" เป็นข้อความประกอบ) ⇒ **ไม่มีผลกับราคาทุกกรณี** แต่ตัวอ่านรหัสเตือนเมื่อ ไม่ได้ระบุ ·
   * อยู่นอกรายการของช่อง · ไม่คู่กับขนาดแกน · ใช้กับรุ่นย่อยที่ทำไม่ได้ (เจ้าของเคาะ 2026-10-05: "ให้ราคาเท่ากัน แต่แจ้งเตือน")
   *   · `fits` ขนาดเขี้ยวล็อค → ขนาดแกน (ไม่รวมตัวอักษรวัสดุ) ที่ใช้คู่กัน = ตาราง "ใช้กับขนาดแกน" ของแคตตาล็อก ∪ คอลัมน์ B ของชีต
   *   · `only` ขนาดเขี้ยวล็อค → รุ่นย่อย (แกน `submodel` ของตารางราคาตั้ง) ที่ทำได้
   */
  connector?: { slot: string; fits: Record<string, string[]>; only?: Record<string, { submodel: string; source: string }> };
}

/** ค่าที่กรอกในช่อง — ตัวเดียวกันทั้งตอนอ่านรหัสออกมาและตอนประกอบกลับ */
export interface TsForm {
  family: TsFamily;
  /** ช่อง → รหัสในช่องนั้น (`''` = None ของแคตตาล็อก / ช่องตัวเลขที่เว้นว่าง) — ตัวเลขเก็บเป็นข้อความตามที่พิมพ์ */
  values: Record<string, string>;
  /** บวกเพิ่มที่ติ๊ก (ไม่อยู่ในรหัส) */
  addons?: string[];
  /** ท่อนต่อท้ายที่ไม่อยู่ในแคตตาล็อก (`S000` · `TM000` — ตัวอักษรตามด้วยตัวเลข) ตามลำดับเดิม — ประกอบกลับเป็น `-S000` */
  extras?: string[];

  // ── ของ `readTsFormLoose` เท่านั้น (รหัสที่ประกอบกลับตรง ๆ ไม่ได้) — ไม่มีช่องเหล่านี้ = รหัสตรงแคตตาล็อกทุกตัวอักษร ──
  /**
   * ช่อง → ข้อความตามที่รหัสเขียน เมื่อไม่ใช่รหัสของตัวเลือกตรงตัว: ค่านอกแคตตาล็อก (`M12` · แกน `4`) ·
   * ค่ามาตรฐานที่เขียนออกมา (`M5`) · `5/16"` ที่มีเครื่องหมายนิ้ว — `buildTsCode` ใช้ค่านี้ก่อน `values`
   * หน้าจอลบช่องนี้ทิ้งเมื่อคนเลือกค่าใหม่ในช่องนั้น
   */
  written?: Record<string, string>;
  /** ความยาวสายเขียนเป็นเซนติเมตร (`+30cm`) / มิลลิเมตร (`+400mm`) — `values.cl` เป็นตัวเลขตามที่เขียน ไม่แปลงเป็นเมตร */
  clUnit?: 'cm' | 'mm';
  /** TS_-11 เขียนสายติดกับ M (`+5MPU`) แทน `+5M-PU` ของแคตตาล็อก */
  cableNoDash?: boolean;
  /** ท่อนที่อ่านไม่ออกหลังเลขรุ่น (`-L` ของ `TSK-01-L(M6)` · `S` ของ `TSK-01S`) — ประกอบกลับที่ตำแหน่งเดิม */
  headJunk?: string;
  /** ท้ายรหัสตามที่เขียนทีละท่อนพร้อมตัวคั่น (`-SP` · `-S000` · `+MP` · `.`) — ใช้แทน `extras` */
  tail?: string[];
  /**
   * ช่องที่รหัส **ไม่ได้เขียนเลย** (ไม่มีวงเล็บเกลียว · ไม่มี `x` · ไม่มีท่อนสาย) — `buildTsCode` ไม่เติมค่ามาตรฐานลงไป
   * ⇒ ประกอบกลับได้รูปเดิม · หน้าจอเอาช่องออกจากรายการนี้เมื่อคนกรอกช่องนั้น
   */
  omit?: string[];
  /**
   * ช่องที่ไม่ตรงแคตตาล็อก — **เซิร์ฟเวอร์คำนวณให้ ห้ามรับจากหน้าจอ** · `off` = ค่านอกแคตตาล็อกที่คิดได้ ·
   * `ask` = ต้องขอราคาจากฝ่ายผลิต (`ProductConfig.askPrice`) · `unread` = ตัวอ่านรหัสอ่านท่อนนี้ไม่ออก ·
   * `missing` = รหัสไม่ได้บอก (ช่องที่แคตตาล็อกไม่มี None)
   */
  issues?: Record<string, 'off' | 'ask' | 'unread' | 'missing'>;
}

